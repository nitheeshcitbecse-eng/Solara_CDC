type JobSeed = {
  id: string;
  hirerId: string;
  sectorId: string | null;
  proposedSectorName?: string;
  title: string;
  description: string;
  salary: Salary;
  shift: Shift;
  timings?: [string, string];
  openings?: number;
  location: JobLocation;
  requirements: string[];
  languages: LanguageCode[];
  benefits: string[];
  photos: MockMediaKey[];
  status?: DbJob['status'];
  daysAgo: number;
  photoNote?: string;
};

function build(now: number, seed: JobSeed): DbJob {
  const createdAt = ago(now, { days: seed.daysAgo, hours: 3 });
  const hasPhotos = seed.photos.length > 0;
  const analysis = hasPhotos
    ? analyseWorkplacePhotos({
        photoNames: seed.photos.map((key) => `${key}.jpg`),
        note: seed.photoNote ?? '',
        sectorSlug: seed.sectorId ? (SLUG_BY_SECTOR[seed.sectorId] ?? null) : null,
      })
    : null;
  return {
    id: seed.id,
    hirerId: seed.hirerId,
    sectorId: seed.sectorId,
    proposedSectorName: seed.proposedSectorName ?? null,
    sectorDecision: seed.sectorId ? 'match' : 'new',
    title: seed.title,
    description: seed.description,
    salary: seed.salary,
    shift: seed.shift,
    timings: seed.timings ? { start: seed.timings[0], end: seed.timings[1] } : null,
    openings: seed.openings ?? 1,
    location: seed.location,
    requirements: seed.requirements,
    languages: seed.languages,
    benefits: seed.benefits,
    photos: seed.photos.map((key, index) => ({ id: `${seed.id}_ph${index + 1}`, url: mediaRef(key) })),
    difficulty: analysis?.difficulty ?? null,
    safety: analysis?.safety ?? null,
    status: seed.status ?? 'active',
    createdAt,
    updatedAt: createdAt,
    analysis: analysis ? { startedAt: createdAt, photoNames: seed.photos.map((key) => `${key}.jpg`), note: seed.photoNote ?? '', result: analysis } : null,
  };
}

