/** Maps a reverse-geocoded region ("TN", "Tamil Nadu", "NCT of Delhi") to our list, if possible. */
export function matchIndianState(region: string | null | undefined): string | null {
  if (!region) return null;
  const normalized = region.toLowerCase().replace(/^nct of\s+/, '').trim();
  return INDIAN_STATES.find((state) => state.toLowerCase() === normalized) ?? null;
}
